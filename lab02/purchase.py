# purchase.py — стоимость покупки и сдача
# Лабораторная работа 2, обязательное задание 2.
# Деньги хранятся в целых рублях, поэтому float здесь не используется.

price = int(input("Цена одной тетради, руб.: "))
count = int(input("Количество тетрадей: "))
paid = int(input("Переданная сумма, руб.: "))

cost = price * count
change = paid - cost

print(f"Стоимость: {cost} руб.")
print(f"Сдача: {change} руб.")
