# variant.py — вариант 11: заполненность парковки
# Лабораторная работа 3, вариант 11.
# 0-59: Много мест, 60-89: Мало мест, 90-100: Почти занята,
# иначе: Ошибка диапазона.

occupancy = int(input("Заполненность парковки, %: "))

if occupancy < 0 or occupancy > 100:
    print("Ошибка диапазона")
elif occupancy <= 59:
    print("Много мест")
elif occupancy <= 89:
    print("Мало мест")
else:
    print("Почти занята")
